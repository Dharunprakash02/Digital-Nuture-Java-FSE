/**
 * Objective: Understand Java's primitive data types.
 * Task: Declare variables of different primitive types and display their values.
 */
public class DataTypeDemo {
    public static void main(String[] args) {
        System.out.println("=== Primitive Data Types in Java ===");
        
        // Declaring and initializing primitive data types
        int intVar = 42;
        float floatVar = 3.14f;
        double doubleVar = 2.7182818284;
        char charVar = 'J';
        boolean booleanVar = true;
        
        // Displaying variables
        System.out.println("Integer (int): " + intVar);
        System.out.println("Float (float): " + floatVar);
        System.out.println("Double (double): " + doubleVar);
        System.out.println("Character (char): " + charVar);
        System.out.println("Boolean (boolean): " + booleanVar);
    }
}
